"""core/mass_units.py — ЕДИНИЦА МАССЫ ОТВЕСА проекта (iter97).

Мотивация (технолог 14.08.2026). Массу в выгрузках печатали ДВА разных
слоя и в РАЗНЫХ единицах: расход сырья и рецепт ветки — в килограммах
(жёсткая константа ``campaign_ui.MASS_UNIT``), а карта навески — в
граммах (``recipe_weighing_dataframe``). В одном файле жили два масштаба
записи, и оператор сверял «0,0004 кг» с «0,4 г» глазами. Плюс сама
константа не выбиралась: для замеса 10 кг мелкие компоненты (UV
0,05 phr) в килограммах вырождаются в нули после округления.

Поэтому единица массы отвеса — ПАРАМЕТР ПРОЕКТА
(:attr:`MixtureProcessRunner.batch_mass_unit`), задаётся один раз и
тащится во все таблицы и листы Excel. Здесь — чистое ядро этого
параметра: список допустимых единиц, нормализация ввода и перевод.

Границы ответственности:

  * ВНУТРИ кода масса всегда в КИЛОГРАММАХ (``batch_kg``) — так считают
    ядро (:meth:`PhrSpec.fraction_bounds` × вес замеса) и хелперы
    навески. Единица отвеса — слой ПОКАЗА: перевод происходит на границе
    «в таблицу / из поля формы», а не в арифметике;
  * единица НЕ связана с ``mass_unit`` экономики (цена ₽/кг и ρ кг/изд):
    та единица обязана совпадать у цены и у плотности, иначе
    себестоимость требует переводных коэффициентов (см.
    :meth:`MixtureProcessRunner.set_project_economics`). Отвес же удобно
    вести в граммах, а цену — за килограмм; связывать их одним полем
    значило бы ломать одно ради другого.

Все функции ЧИСТЫЕ (без numpy-состояния, без Streamlit) — тестируются
напрямую.
"""
from __future__ import annotations

from math import log10 as _log10
from typing import Dict, Tuple

__all__ = ["MASS_UNITS", "MASS_UNIT_NAMES", "DEFAULT_MASS_UNIT",
           "MASS_ROUND_DIGITS", "normalize_mass_unit", "mass_from_kg",
           "mass_to_kg", "mass_column_label"]

#: Допустимые единицы массы отвеса → сколько ЭТИХ единиц в одном килограмме.
#: Набор намеренно короткий: это цеховые единицы отвеса, а не полный
#: справочник СИ. Расширение — осознанное решение, а не «на всякий случай»:
#: каждая новая единица появляется в подписях всех таблиц проекта.
MASS_UNITS: Dict[str, float] = {"г": 1000.0, "кг": 1.0, "т": 0.001}

#: Порядок для выпадающего списка UI (от мелкой к крупной).
MASS_UNIT_NAMES: Tuple[str, ...] = ("г", "кг", "т")

#: Единица по умолчанию — килограмм: так вели выгрузки до iter97, и старые
#: проекты (без ключа в ``campaign.json``) обязаны читаться без сдвига чисел.
DEFAULT_MASS_UNIT = "кг"

#: Знаков после запятой при показе массы — БАЗА для килограмма: 4 знака =
#: прежнее поведение килограммовых колонок (разрешение 0,1 г).
MASS_ROUND_DIGITS = 4

#: Знаков после запятой ПО ЕДИНИЦАМ. Разрешение показа не должно быть грубее
#: килограммового: «4 знака» в тоннах означали бы шаг 100 г, и мелкая навеска
#: исчезала бы при переводе. Поэтому у КРУПНОЙ единицы знаков больше на
#: порядок величины (т: 4 + 3 = 7 ⇒ шаг 0,1 мг), у мелкой — база (в граммах 4
#: знака избыточны, но безвредны и сохраняют отвесы вида 0,04 г).
_DIGITS: Dict[str, int] = {
    unit: MASS_ROUND_DIGITS + max(0, round(-_log10(factor)))
    for unit, factor in MASS_UNITS.items()
}

#: Синонимы ввода: человек пишет единицу руками (в том числе латиницей и
#: полным словом). Приводим к каноническому обозначению — иначе «kg» и «кг»
#: дали бы два разных заголовка колонки для одной и той же величины.
_ALIASES: Dict[str, str] = {
    "g": "г", "гр": "г", "грамм": "г", "граммы": "г", "gram": "г",
    "kg": "кг", "килограмм": "кг", "килограммы": "кг", "kilogram": "кг",
    "t": "т", "тонна": "т", "тонны": "т", "ton": "т", "tonne": "т",
}


def normalize_mass_unit(unit: object, *, default: str = DEFAULT_MASS_UNIT
                        ) -> str:
    """Ввод пользователя → каноническое обозначение единицы массы.

    Пусто/``None`` → ``default`` (это «не задано», а не ошибка: старые
    проекты и незаполненное поле формы означают прежнее поведение).
    Неизвестная единица — ЯВНЫЙ отказ (A0.6): молчаливый откат на
    килограммы напечатал бы «0,0004 кг» там, где человек просил граммы, и
    расхождение обнаружилось бы только на весах.
    """
    txt = str(unit or "").strip()
    if not txt:
        return str(default)
    if txt in MASS_UNITS:
        return txt
    low = txt.lower().replace(".", "")
    if low in MASS_UNITS:
        return low
    if low in _ALIASES:
        return _ALIASES[low]
    raise ValueError(
        f"Неизвестная единица массы отвеса {txt!r}. Допустимы: "
        + ", ".join(MASS_UNIT_NAMES)
        + " (масса внутри проекта считается в килограммах, единица — только "
          "для показа и выгрузок).")


def mass_from_kg(value_kg: float, unit: object = DEFAULT_MASS_UNIT) -> float:
    """Килограммы → выбранная единица массы (значение ПОКАЗА, округлённое).

    Округление здесь, а не у каждого вызывающего: одна и та же навеска
    обязана выглядеть одинаково в плане, в расходе сырья и в базе опытов.
    Число знаков — по единице (``_DIGITS``): разрешение показа одинаково во
    всех единицах и не грубее килограммового.
    """
    u = normalize_mass_unit(unit)
    return round(float(value_kg) * MASS_UNITS[u], _DIGITS[u])


def mass_to_kg(value: float, unit: object = DEFAULT_MASS_UNIT) -> float:
    """Значение в выбранной единице → КИЛОГРАММЫ (для арифметики ядра).

    Обратное к :func:`mass_from_kg` БЕЗ округления: введённый в форме вес
    замеса идёт дальше в ``batch_grams_per_phr`` и в масштаб δ_phr, и
    округление на этом пути сдвигало бы разрешение навески.
    """
    u = normalize_mass_unit(unit)
    return float(value) / MASS_UNITS[u]


def mass_column_label(name: str, unit: object = DEFAULT_MASS_UNIT) -> str:
    """Заголовок массовой колонки таблицы: ``«TiO2 (г)»``.

    Единый источник имени: заголовки читают и тесты, и Excel-выгрузки, и
    подписи UI — собирать их строками по месту значило бы разъезд.
    """
    return f"{name} ({normalize_mass_unit(unit)})"
