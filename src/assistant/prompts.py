def routing_block() -> str:
    """Табличка «типовой вопрос → маршрут» словами (те же golden-сценарии)."""
    lines = ["МАРШРУТИЗАЦИЯ ТИПОВЫХ ВОПРОСОВ (ASSISTANT_SPEC §8):"]
    for sc in GOLDEN_SCENARIOS:
        tools = ", ".join(f"`{t}`" for t in sc.tools) or "инструменты не нужны"
        lines.append(f"  {sc.id}. {sc.title} → {tools}")
        lines.append(f"       {sc.rule}")
    return "\n".join(lines)


def architect_system_prompt(*, project: str = "", spec_hash: str = "",
                            web: bool = False, has_runner: bool = True,
                            n_attachments: int = 0,
                            kinds: Optional[Sequence[str]] = None,
                            extra: str = "") -> str:
    """Собрать системный промпт архитектора под текущее состояние сессии.

    ``has_runner=False`` — проект ещё не собран: об этом сказано прямо, иначе
    модель начнёт «объяснять» геометрию, которой нет. ``web`` включает
    напоминание про уровень знания L2 у сетевых утверждений.
    """
    # iter74: UI_BLOCK стоит ПЕРЕД форматом ответа — «где нажать» и язык ответа
    # относятся к содержанию, а FORMAT_BLOCK описывает только оформление.
    parts: List[str] = [ROLE_BLOCK, KNOWLEDGE_BLOCK, LIMITS_BLOCK, UI_BLOCK,
                        FORMAT_BLOCK]

    ctx: List[str] = ["КОНТЕКСТ СЕССИИ:"]
    ctx.append(f"  • проект: {project or '— (не выбран)'}")
    if spec_hash:
        ctx.append(f"  • spec_hash активной спеки: {spec_hash} — единственный "
                   f"источник истины о геометрии")
    if not has_runner:
        # iter73: раньше здесь стояло «зови собрать проект» — и модель звала
        # человека в форму, хотя собрать проект она может ПРЕДЛОЖИТЬ сама
        # пакетом. Обратное тоже важно: применять пакет СПЕКИ сейчас некуда.
        ctx.append("  • проект НЕ собран: расчётной модели и базы опытов нет. "
                   "Вопросы про проверку плана и расчёты честно оставляй без "
                   "чисел. Заводить проект — твоя работа: собери пакет ПРОЕКТА "
                   "(состав + отклики + процесс-оси) и предложи "
                   "`propose_project`; пакет СПЕКИ сейчас применять НЕКУДА, "
                   "человек нажмёт кнопку и не получит результата.")
        # iter76: до сборки данные живут в ПОЛЯХ формы «🆕 Новый проект» —
        # без этих двух строк модель их не видела и на просьбу «поправь верх
        # частоты» отвечала пакетом проекта с нуля, затирая ручной ввод.
        ctx.append("  • поля формы «🆕 Новый проект» уже могут быть заполнены "
                   "(человеком или принятым пакетом): смотри их через "
                   "`get_setup_fields`. Точечное изменение заполненных полей "
                   "предлагай `propose_setup_fields` ({ключ_поля: значение}) — "
                   "не пересобирай пакет проекта целиком ради одной правки.")
    if n_attachments:
        ctx.append(f"  • вложений в сессии: {n_attachments} — читай их "
                   f"`read_attachment`, не пересказывай по имени файла.")
    # iter68: у окна ассистента появились картинки на вход и графика на выход.
    # Без этих двух строк модель либо отказывается «я не вижу изображений»,
    # либо пересказывает числа словами там, где уместен график.
    ctx.append("  • изображения: пользователь может приложить СКРИНШОТ или фото "
               "паспорта — они приходят прямо в сообщении, смотри их сам. Если "
               "картинка не видна, скажи об этом, а не описывай по догадке.")
    ctx.append("  • график и таблицу можно ПОКАЗАТЬ: в `run_python` сохрани "
               "файл в текущий каталог (`plt.savefig('name.png')` с backend "
               "'Agg', `df.to_csv('name.csv', index=False)`) — он попадёт в "
               "кампанию и отрисуется пользователю. Зависимость (например "
               "hi_phi от температуры) показывай кривой, а не списком чисел.")
    ctx.append("  • интернет: " + ("ВКЛЮЧЁН (`:online`). Всё, что пришло из "
                                   "сети, помечай как L2 — локальный факт цеха "
                                   "его отменяет." if web else
                                   "выключен: ссылок на веб не выдумывай."))
    parts.append("\n".join(ctx))

    catalog = tool_catalog(kinds)
    if catalog:
        parts.append("ИНСТРУМЕНТЫ (вызывай их, а не память):\n" + catalog)
    parts.append(routing_block())
    if extra.strip():
        parts.append(extra.strip())
    return "\n\n".join(parts)


