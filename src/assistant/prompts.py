SECTIONS = ("ОТВЕТ", "ЧИСЛА", "PATCH", "OPEN_QUESTIONS")

_HEAD_RE = re.compile(r"^\s*#{1,6}\s*([A-ZА-Я_]+)\s*$", re.MULTILINE)


def parse_sections(text: str) -> Dict[str, str]:
    """Ответ модели → словарь секций формата (пустые разделы отбрасываются).

    Нужен UI и журналу: из раздела ``PATCH`` собирается панель предложений, из
    ``OPEN_QUESTIONS`` — список вопросов к человеку. Разбор ЧИСТЫЙ, поэтому
    формат проверяется тестом, а не глазами.
    """
    src = str(text or "")
    heads = list(_HEAD_RE.finditer(src))
    out: Dict[str, str] = {}
    for i, m in enumerate(heads):
        name = m.group(1).strip()
        end = heads[i + 1].start() if i + 1 < len(heads) else len(src)
        body = src[m.end():end].strip()
        if body:
            out[name] = body
    return out


def pop_section(text: str, name: str) -> Tuple[str, str]:
    """Вырезать раздел из ответа: ``(остаток, тело раздела)``.

    Нужна показу: раздел ``ЧИСЛА`` док рисует ОТДЕЛЬНО (свёрнутым блоком под
    ответом), а не строкой в общем потоке — интерпретация и измерение не
    должны выглядеть одинаково весомо. Резать текст в виджетах нельзя: разбор
    обязан быть чистым и проверяемым тестом.

    Раздела нет — возвращается исходный текст и пустая строка. Пустой раздел
    (заголовок без тела) тоже вырезается: заголовок «ЧИСЛА» без чисел хуже,
    чем его отсутствие.
    """
    src = str(text or "")
    want = str(name or "").strip()
    heads = list(_HEAD_RE.finditer(src))
    for i, m in enumerate(heads):
        if m.group(1).strip() != want:
            continue
        end = heads[i + 1].start() if i + 1 < len(heads) else len(src)
        body = src[m.end():end].strip()
        rest = (src[:m.start()].rstrip() + "\n\n" + src[end:].lstrip()).strip()
        return rest, body
    return src.strip(), ""


def missing_sections(text: str, *, required: Sequence[str] = ("ОТВЕТ",)
                     ) -> List[str]:
    """Какие обязательные разделы ответа отсутствуют."""
    have = parse_sections(text)
    return [r for r in required if r not in have]
